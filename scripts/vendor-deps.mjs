#!/usr/bin/env node
// Copies the few runtime files the decks need out of node_modules into vendor/,
// so the repo works from a plain clone and from GitHub Pages with no install.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { join, resolve, dirname, basename } from "node:path";

const root = resolve(import.meta.dirname, "..");
const nm = join(root, "node_modules");
const out = join(root, "vendor");

mkdirSync(join(out, "reveal"), { recursive: true });
mkdirSync(join(out, "reveal/plugin/highlight"), { recursive: true });
mkdirSync(join(out, "reveal/plugin/notes"), { recursive: true });
mkdirSync(join(out, "fonts/files"), { recursive: true });

for (const f of ["dist/reveal.js", "dist/reveal.css", "dist/reset.css"])
  copyFileSync(join(nm, "reveal.js", f), join(out, "reveal", basename(f)));
for (const f of ["plugin/highlight/highlight.js", "plugin/highlight/monokai.css"])
  copyFileSync(join(nm, "reveal.js", f), join(out, "reveal/plugin/highlight", basename(f)));
// speaker view is a real page the notes plugin opens in a popup, so it has to come too
for (const f of ["plugin/notes/notes.js", "plugin/notes/speaker-view.html"])
  copyFileSync(join(nm, "reveal.js", f), join(out, "reveal/plugin/notes", basename(f)));

// One stylesheet for all families, latin only. Keeps ~200KB instead of 11MB.
const families = ["inter", "jetbrains-mono", "shantell-sans"];
let css = "/* generated by scripts/vendor-deps.mjs — latin subsets only */\n";
for (const fam of families) {
  const dir = join(nm, "@fontsource-variable", fam);
  const src = readFileSync(join(dir, "index.css"), "utf8");
  for (const block of src.match(/@font-face\s*\{[^}]*\}/g) ?? []) {
    const file = block.match(/url\(\.\/files\/([^)]+?)\)/)?.[1];
    if (!file || !/-latin-[a-z]*-?normal\.woff2/.test(file) || /-latin-ext-/.test(file)) continue;
    copyFileSync(join(dir, "files", file), join(out, "fonts/files", file));
    css += block
      .replace(/url\(\.\/files\//g, "url(./files/")
      .replace(/format\('woff2-variations'\)/g, "format('woff2')") + "\n";
  }
}
writeFileSync(join(out, "fonts/fonts.css"), css);

// Point every deck at vendor/ instead of node_modules/
const decks = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !["node_modules", ".git", "vendor", "scripts", "shared", "assets", "docs"].includes(d.name))
  .map((d) => join(root, d.name, "index.html"))
  .concat(join(root, "index.html"));

let touched = 0;
for (const file of decks) {
  let html;
  try { html = readFileSync(file, "utf8"); } catch { continue; }
  const before = html;
  const up = file === join(root, "index.html") ? "./" : "../";
  html = html.replace(new RegExp(`${up.replace(".", "\\.")}node_modules/reveal\\.js/dist/`, "g"), `${up}vendor/reveal/`);
  html = html.replace(new RegExp(`${up.replace(".", "\\.")}node_modules/reveal\\.js/plugin/`, "g"), `${up}vendor/reveal/plugin/`);
  // three fontsource links collapse into one vendored stylesheet
  html = html.replace(
    new RegExp(`[ \\t]*<link rel="stylesheet" href="${up.replace(".", "\\.")}node_modules/@fontsource-variable/[^"]+">\\n`, "g"),
    "");
  if (before !== html && !html.includes("vendor/fonts/fonts.css"))
    html = html.replace(/(<link rel="stylesheet" href="[^"]*vendor\/reveal\/reset\.css">\n)/,
      `$1  <link rel="stylesheet" href="${up}vendor/fonts/fonts.css">\n`);
  if (before !== html) { writeFileSync(file, html); touched++; }
}
console.log(`vendored reveal + ${families.length} font families; rewrote ${touched} html files`);
